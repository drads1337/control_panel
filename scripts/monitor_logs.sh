#!/bin/bash
# Мониторинг логов Docker для диагностики доступности домена

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

cd "$PROJECT_ROOT"

echo "=========================================="
echo "Мониторинг логов Docker"
echo "=========================================="
echo ""
echo "Нажмите Ctrl+C для выхода"
echo ""
echo "Сейчас будут показаны последние 50 строк логов Nginx,"
echo "затем будет мониторинг в реальном времени..."
echo ""
echo "Попробуйте подключиться извне (http://ovrin.xyz) -"
echo "в логах должны появиться записи с вашим IP адресом"
echo ""
echo "=========================================="
echo ""

# Показать последние 50 строк логов Nginx
echo "=== Последние 50 строк логов Nginx ==="
docker-compose logs nginx --tail=50 2>&1 | tail -50
echo ""

# Показать последние 20 строк логов API
echo "=== Последние 20 строк логов API ==="
docker-compose logs api --tail=20 2>&1 | tail -20
echo ""

echo "=========================================="
echo "Мониторинг в реальном времени (Nginx)..."
echo "=========================================="
echo ""
echo "Ожидание запросов... Попробуйте подключиться извне."
echo ""

# Мониторинг в реальном времени
docker-compose logs -f nginx 2>&1

